import os

_STATE = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".theme")


def load_last():
    """Remember the last skin (written to .theme by F2)."""
    try:
        with open(_STATE, "r", encoding="utf-8") as fh:
            name = fh.read().strip()
    except OSError:
        return None
    for th in ALL:
        if th.name == name:
            return th
    return None


def save_last(th):
    try:
        with open(_STATE, "w", encoding="utf-8") as fh:
            fh.write(th.name + "\n")
    except OSError:
        pass


def get(name):
    for th in ALL:
        if th.name == name:
            return th
    return POCKET


def cycle(th):
    i = ALL.index(th) if th in ALL else 0
    return ALL[(i + 1) % len(ALL)]
